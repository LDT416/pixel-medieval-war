import assert from 'node:assert/strict';
import {build} from 'esbuild';
const bundled=await build({stdin:{contents:"export {SimWorld} from './src/sim/world';export {supportOptions} from './src/sim/units/support';export {variants,formationTicks,setupTicks,travelFatigue,restRecovery} from './src/sim/units/roster'",resolveDir:process.cwd()},bundle:true,platform:'node',format:'esm',write:false});
const {SimWorld,supportOptions,variants,formationTicks,setupTicks,travelFatigue,restRecovery}=await import('data:text/javascript;base64,'+Buffer.from(bundled.outputFiles[0].text).toString('base64'));
const w=new SimWorld(3600,23757);
const roles=new Set(w.companies.map(c=>c.variant).filter(Boolean));
assert.deepEqual([...roles].sort(),Object.keys(variants).sort());
for(const c of w.companies.filter(c=>c.variant))assert.equal(variants[c.variant].base,c.kind);
const company=variant=>w.companies.find(c=>c.variant===variant);
assert.equal(formationTicks(company('voltigeur'),'line',false),44);
assert.equal(formationTicks(company('voltigeur'),'line',true),66);
assert.equal(setupTicks(company('horse_battery')),60);
assert.equal(setupTicks(company('howitzer')),75);
assert.equal(travelFatigue(company('hussar')),.8);
assert.equal(travelFatigue(company('lancer')),1);
assert.equal(restRecovery(company('lancer')),.85);assert.equal(restRecovery(company('rifles')),1.2);
assert.equal(restRecovery(company('hussar')),1);
const front=w.companies.find(c=>c.line===0);
front.ammo=0;assert.equal(supportOptions(front,true)[0].action,'rotate');
assert.equal(supportOptions(front,false)[0].action,'continue');
front.ammo=front.alive*40;assert.equal(supportOptions(front,true)[0].action,'continue');
// Recovery uses the actual logistics clock and requires a stocked friendly depot.
const rifles=company('rifles'),depot=w.logistics.wagons.find(v=>v.faction===rifles.faction);
rifles.x=depot.x;rifles.y=depot.y;rifles.fatigue=.5;rifles.vx=rifles.vy=0;
w.tick=60;w.logistics.step(w);
assert.ok(Math.abs(rifles.fatigue-.494)<1e-9);
rifles.x=0;rifles.y=0;w.tick=90;w.logistics.step(w);
assert.ok(Math.abs(rifles.fatigue-.489)<1e-9);
console.log(JSON.stringify({variants:[...roles],actions:supportOptions(front,true)}));
